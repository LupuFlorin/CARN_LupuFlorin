def get_datasets(dataset_name, augment=False, use_autoaugment=False):
    """Enhanced dataset loading with advanced augmentation"""

    if dataset_name == 'MNIST':
        num_classes = 10
        mean = (0.1307,)
        std = (0.3081,)

        if augment:
            train_t = [
                transforms.RandomAffine(degrees=10, translate=(0.1, 0.1)),
                transforms.ToTensor(),
                transforms.Normalize(mean, std)
            ]
        else:
            train_t = [transforms.ToTensor(), transforms.Normalize(mean, std)]

        val_t = [transforms.ToTensor(), transforms.Normalize(mean, std)]

        train = torchvision.datasets.MNIST(root='data', train=True, download=True,
                                          transform=transforms.Compose(train_t))
        val = torchvision.datasets.MNIST(root='data', train=False, download=True,
                                        transform=transforms.Compose(val_t))
        return train, val, num_classes

    elif dataset_name in ['CIFAR10', 'CIFAR100']:
        if dataset_name == 'CIFAR10':
            ds = torchvision.datasets.CIFAR10
            num_classes = 10
            mean = (0.4914, 0.4822, 0.4465)
            std = (0.2470, 0.2435, 0.2616)
        else:
            ds = torchvision.datasets.CIFAR100
            num_classes = 100
            # CIFAR-100 specific normalization (better than CIFAR-10)
            mean = (0.5071, 0.4867, 0.4408)
            std = (0.2675, 0.2565, 0.2761)

        if augment:
            # STRONG AUGMENTATION FOR >70% ACCURACY
            train_transforms = [
                transforms.RandomCrop(32, padding=4),
                transforms.RandomHorizontalFlip(),
                transforms.ColorJitter(brightness=0.2, contrast=0.2,
                                     saturation=0.2, hue=0.1),
                transforms.RandomRotation(15),
            ]

            # Add AutoAugment if requested
            if use_autoaugment:
                train_transforms.append(
                    transforms.AutoAugment(transforms.AutoAugmentPolicy.CIFAR10)
                )

            train_transforms.extend([
                transforms.ToTensor(),
                transforms.Normalize(mean, std),
                # RandomErasing (Cutout variant) - CRITICAL for >70%
                transforms.RandomErasing(p=0.5, scale=(0.02, 0.33),
                                       ratio=(0.3, 3.3), value='random'),
            ])
        else:
            train_transforms = [
                transforms.ToTensor(),
                transforms.Normalize(mean, std)
            ]

        val_transforms = [
            transforms.ToTensor(),
            transforms.Normalize(mean, std)
        ]

        train = ds(root='data', train=True, download=True,
                  transform=transforms.Compose(train_transforms))
        val = ds(root='data', train=False, download=True,
                transform=transforms.Compose(val_transforms))

        return train, val, num_classes

    elif dataset_name in ['OXFORDIIIT_PET', 'OXFORD-IIIT-PET']:
        num_classes = 37
        from torchvision.datasets import OxfordIIITPet

        base_transform = [transforms.Resize((224, 224))]

        if augment:
            base_transform += [
                transforms.RandomHorizontalFlip(),
                transforms.RandomRotation(15),
                transforms.ColorJitter(brightness=0.2, contrast=0.2, saturation=0.2),
            ]

        base_transform += [
            transforms.ToTensor(),
            transforms.Normalize((0.485, 0.456, 0.406), (0.229, 0.224, 0.225))
        ]

        train = OxfordIIITPet(root='data', download=True,
                             transform=transforms.Compose(base_transform),
                             target_types='category')
        val = OxfordIIITPet(root='data', download=True,
                           transform=transforms.Compose(base_transform),
                           target_types='category')

        return train, val, num_classes

    else:
        raise ValueError(f'Unknown dataset: {dataset_name}')

