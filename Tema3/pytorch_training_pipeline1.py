class SimpleMLP(nn.Module):
  def __init__(self, input_dim=3*32*32, hidden=1024, num_classes=10):
    super().__init__()
    self.net = nn.Sequential(
      nn.Flatten(),
      nn.Linear(input_dim, hidden),
      nn.ReLU(inplace=True),
      nn.Dropout(0.2),
      nn.Linear(hidden, hidden//2),
      nn.ReLU(inplace=True),
      nn.Linear(hidden//2, num_classes)
    )
  def forward(self,x):
    return self.net(x)




def get_model(name, num_classes, pretrained=False):
  name_lower = name.lower()
  if 'resnet' in name_lower or name_lower.startswith('resnest'):
    if timm is None:
      raise RuntimeError('timm is required to load these models. pip install timm')
    model = timm.create_model(name, pretrained=pretrained, num_classes=num_classes)
    return model
  elif name_lower=='mlp':
    # Determine input dims from dataset in training code
    return SimpleMLP(num_classes=num_classes)
  else:
    # try to load timm
    if timm is None:
      raise RuntimeError('timm is required to load this model')
    return timm.create_model(name, pretrained=pretrained, num_classes=num_classes)

class SAM(torch.optim.Optimizer):
    def __init__(self, params, base_optimizer, rho=0.05, adaptive=False, **kwargs):
        assert rho >= 0.0, f"Invalid rho, should be non-negative: {rho}"

        defaults = dict(rho=rho, adaptive=adaptive, **kwargs)
        super(SAM, self).__init__(params, defaults)

        self.base_optimizer = base_optimizer(self.param_groups, **kwargs)
        self.param_groups = self.base_optimizer.param_groups
        self.defaults.update(self.base_optimizer.defaults)

    @torch.no_grad()
    def first_step(self, zero_grad=False):
        grad_norm = self._grad_norm()
        for group in self.param_groups:
            scale = group["rho"] / (grad_norm + 1e-12)

            for p in group["params"]:
                if p.grad is None: continue
                self.state[p]["old_p"] = p.data.clone()
                e_w = (torch.pow(p, 2) if group["adaptive"] else 1.0) * p.grad * scale.to(p)
                p.add_(e_w)  # climb to the local maximum "w + e(w)"

        if zero_grad: self.zero_grad()

    @torch.no_grad()
    def second_step(self, zero_grad=False):
        for group in self.param_groups:
            for p in group["params"]:
                if p.grad is None: continue
                p.data = self.state[p]["old_p"]  # get back to "w" from "w + e(w)"

        self.base_optimizer.step()  # do the actual "sharpness-aware" update

        if zero_grad: self.zero_grad()

    @torch.no_grad()
    def step(self, closure=None):
        assert closure is not None, "Sharpness Aware Minimization requires closure, but it was not provided"
        closure = torch.enable_grad()(closure)  # the closure should do a full forward-backward pass

        self.first_step(zero_grad=True)
        closure()
        self.second_step()

    def _grad_norm(self):
        shared_device = self.param_groups[0]["params"][0].device  # put everything on the same device, in case of model parallelism
        norm = torch.norm(
                    torch.stack([
                        ((torch.abs(p) if group["adaptive"] else 1.0) * p.grad).norm(p=2).to(shared_device)
                        for group in self.param_groups for p in group["params"]
                        if p.grad is not None
                    ]),
                    p=2
               )
        return norm

    def load_state_dict(self, state_dict):
        super().load_state_dict(state_dict)
        self.base_optimizer.param_groups = self.param_groups

# --- Training and evaluation loops ---


def train_epoch(model, loader, criterion, optimizer, device, use_sam=False):
  model.train()
  running_loss = 0.0
  correct = 0
  total = 0
  for x,y in loader:
    x = x.to(device)
    y = y.to(device)
    if use_sam and isinstance(optimizer, SAM):
      outputs = model(x)
      loss = criterion(outputs, y)
      loss.backward()
      optimizer.first_step(zero_grad=True)
      # second forward-backward for SAM
      outputs = model(x)
      loss_second = criterion(outputs, y)
      loss_second.backward()
      optimizer.second_step(zero_grad=True)
    else:
      outputs = model(x)
      loss = criterion(outputs, y)
      optimizer.zero_grad()
      loss.backward()
      optimizer.step()
    running_loss += loss.item() * x.size(0)
    _, preds = outputs.max(1)
    correct += (preds == y).sum().item()
    total += y.size(0)
  return running_loss/total, correct/total




def evaluate(model, loader, criterion, device):
  model.eval()
  running_loss = 0.0
  correct = 0
  total = 0
  with torch.no_grad():
    for x,y in loader:
      x = x.to(device)
      y = y.to(device)
      outputs = model(x)
      loss = criterion(outputs, y)
      running_loss += loss.item() * x.size(0)
      _, preds = outputs.max(1)
      correct += (preds == y).sum().item()
      total += y.size(0)
  return running_loss/total, correct/total


# --- Batch size scheduler (simple) ---


def maybe_increase_batch(epoch, base_bs, schedule_on, factor=2, max_bs=512):
  # schedule_on is list of epochs to increase batch
  bs = base_bs
  for e in schedule_on:
    if epoch >= e:
      bs = min(bs*factor, max_bs)
  return int(bs)

